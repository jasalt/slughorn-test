#!/bin/sh
# Builds the WebGL2 version and commits it to the `pages` branch (an orphan branch that
# holds only the static site, ready for GitHub/GitLab Pages or any static host).
#
# Usage: tools/publish-pages.sh            (ZIG overrides the zig executable)
# Does not push; afterwards run e.g. `git push origin pages`.
set -eu

repo=$(git rev-parse --show-toplevel)
cd "$repo"
zig=${ZIG:-zig}
branch=pages

source_rev=$(git rev-parse --short HEAD)
if [ -n "$(git status --porcelain)" ]; then
	echo "publish-pages: working tree has uncommitted changes; deploying them as $source_rev-dirty" >&2
	source_rev="$source_rev-dirty"
fi

"$zig" build web -Dweb-optimize=small

site=$(mktemp -d)
trap 'git worktree remove --force "$site" 2>/dev/null || rm -rf "$site"' EXIT INT TERM
rmdir "$site"
if git show-ref --verify --quiet "refs/heads/$branch"; then
	git worktree add --quiet "$site" "$branch"
else
	git worktree add --quiet --detach "$site"
	git -C "$site" checkout --quiet --orphan "$branch"
fi
git -C "$site" rm -r --quiet --cached --ignore-unmatch . >/dev/null
find "$site" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +

cp zig-out/web/index.html zig-out/web/vector-feedback.js zig-out/web/vector-feedback.wasm "$site"/
# Serve files as-is on GitHub Pages (no Jekyll processing).
touch "$site/.nojekyll"
cat >"$site/README.md" <<README
# vector-feedback (web build)

Static WebGL2/WebAssembly build of vector-feedback, generated by \`tools/publish-pages.sh\`
from commit $source_rev on master. Serve this directory over HTTP and open \`index.html\`
(append \`?selftest\` to run the on-device selftest). Do not edit by hand.
README

git -C "$site" add -A
if git -C "$site" diff --cached --quiet; then
	echo "publish-pages: $branch already up to date"
else
	git -C "$site" commit --quiet -m "Deploy web build from $source_rev"
	echo "publish-pages: committed $(git rev-parse --short "$branch") to $branch"
fi
